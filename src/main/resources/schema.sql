CREATE TABLE IF NOT EXISTS TB_FIN_TRANSACTION (
    TX_ID VARCHAR(50) PRIMARY KEY,
    ACC_NO_ENC VARCHAR(256) NOT NULL,
    AMOUNT NUMERIC(15, 2) NOT NULL,
    STATUS VARCHAR(20) NOT NULL,
    BIZ_CODE VARCHAR(20) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS TB_SETTLEMENT_LOG (
    LOG_SEQ BIGSERIAL PRIMARY KEY,
    JOB_ID VARCHAR(50) NOT NULL,
    TARGET_DATE VARCHAR(8) NOT NULL,
    PROCESSED_COUNT INT NOT NULL,
    STATUS VARCHAR(20) NOT NULL,
    EXECUTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
